/**
 * Two bitmap fonts drawn directly into the framebuffer (no web fonts, no anti-aliasing):
 *   BIG   5x7 glyphs, 6 px advance, 9 px line  — titles, HUD labels
 *   SMALL 3x5 glyphs, 4 px advance, 7 px line  — dense telemetry
 * Lowercase is drawn as uppercase (a deliberate control-panel look). Private symbols: arrows, play/pause, etc.
 */
import type { Framebuffer } from "./fb";
import { C } from "./palette";

export interface Font {
  gw: number;
  gh: number;
  advance: number;
  line: number;
  glyphs: Map<string, number[]>;
}

function parse(defs: Record<string, string>, w: number): Map<string, number[]> {
  const m = new Map<string, number[]>();
  for (const [ch, rows] of Object.entries(defs)) {
    const bits = rows.trim().split(/\s+/).map((r) => {
      if (r.length !== w) throw new Error(`glyph ${ch}: row ${r} is not ${w} wide`);
      return parseInt(r, 2);
    });
    m.set(ch, bits);
  }
  return m;
}

