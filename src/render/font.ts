export const BIG: Font = { gw: 5, gh: 7, advance: 6, line: 9, glyphs: parse(BIG_DEFS, 5) };
export const SMALL: Font = { gw: 3, gh: 5, advance: 4, line: 7, glyphs: parse(SMALL_DEFS, 3) };

function glyph(font: Font, ch: string): number[] {
  return font.glyphs.get(ch) ?? font.glyphs.get(ch.toUpperCase()) ?? (font.glyphs.get("?") as number[]);
}

export function measure(font: Font, text: string): number {
  const n = [...text].length;
  return n === 0 ? 0 : n * font.advance - 1;
}

export interface TextOpts {
  shadow?: number | null;
  align?: "left" | "center" | "right";
  /** Scale factor (integer) for titles. */
  scale?: number;
  maxWidth?: number;
}

/** Draw a single line of text. Returns the width drawn. */
export function text(fb: Framebuffer, font: Font, str: string, x: number, y: number, color: number, opts: TextOpts = {}): number {
  const scale = opts.scale ?? 1;
  let s = str;
  if (opts.maxWidth !== undefined) {
    const maxChars = Math.floor((opts.maxWidth + 1) / (font.advance * scale));
    if ([...s].length > maxChars) s = [...s].slice(0, Math.max(0, maxChars - 1)).join("") + "…";
  }
  const w = measure(font, s) * scale;
  let x0 = x;
  if (opts.align === "center") x0 = Math.round(x - w / 2);
  else if (opts.align === "right") x0 = x - w;
  const shadow = opts.shadow === undefined ? C.ink : opts.shadow;
  const draw = (ox: number, oy: number, c: number): void => {
    let cx = x0 + ox;
    for (const ch of s) {
      const g = glyph(font, ch);
      for (let row = 0; row < font.gh; row++) {
        const bits = g[row] as number;
        for (let col = 0; col < font.gw; col++) {
          if (bits & (1 << (font.gw - 1 - col))) {
            if (scale === 1) fb.px(cx + col, y + oy + row, c);
            else fb.rect(cx + col * scale, y + oy + row * scale, scale, scale, c);
          }
        }
      }
      cx += font.advance * scale;
    }
  };
  if (shadow !== null) draw(scale, scale, shadow);
  draw(0, 0, color);
  return w;
}

/** Word-wrapped text; returns the number of lines drawn. */
export function wrap(fb: Framebuffer, font: Font, str: string, x: number, y: number, width: number, color: number, opts: TextOpts & { maxLines?: number } = {}): number {
  const maxChars = Math.max(1, Math.floor((width + 1) / font.advance));
  const lines: string[] = [];
  for (const para of str.split("\n")) {
    let line = "";
    for (const word of para.split(/\s+/)) {
      if (!word) continue;
      if (!line) line = word;
      else if (line.length + 1 + word.length <= maxChars) line += " " + word;
      else {
        lines.push(line);
        line = word;
      }
      while (line.length > maxChars) {
        lines.push(line.slice(0, maxChars));
        line = line.slice(maxChars);
      }
    }
    lines.push(line);
  }
  const n = Math.min(lines.length, opts.maxLines ?? lines.length);
  for (let i = 0; i < n; i++) text(fb, font, lines[i] as string, x, y + i * font.line, color, opts);
  return n;
}
